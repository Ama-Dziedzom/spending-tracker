// Expo Config Plugin — adds the LogIt widgets (WidgetKit extension) to iOS.
// Figma section 1037:4555, docs/design-handoff.md §9.
//
// At `expo prebuild` time:
//  1. Copies plugins/widget/* into ios/LogItWidget/, stamping the app version
//  2. Generates ios/LogItWidget/Tokens.swift from constants/tokens.json
//     (each colour has its light and dark value, so widgets follow dark mode)
//  3. Copies the Manrope fonts the widgets use
//  4. Adds the LogItWidget app_extension target, embedded in the app
// The extension reads the snapshot the app writes to the App Group
// (lib/widget-snapshot.ts); the App Group entitlement comes from withShareExtension.

const { withXcodeProject, withDangerousMod } = require('@expo/config-plugins');
const path = require('path');
const fs = require('fs');

const EXT_NAME = 'LogItWidget';
const SRC = path.join(__dirname, 'widget');
const FONTS = ['Manrope_500Medium', 'Manrope_600SemiBold', 'Manrope_700Bold', 'Manrope_800ExtraBold'];
const SWIFT_FILES = ['LogItWidget.swift', 'Tokens.swift'];

const unquote = (s) => String(s || '').replace(/^"(.*)"$/, '$1');

// ─── Tokens.swift ────────────────────────────────────────────────────────────

const camel = (name) =>
  name.split(/[/-]/).map((p, i) => (i === 0 ? p : p.charAt(0).toUpperCase() + p.slice(1))).join('');

function rgba(hex) {
  const h = hex.replace('#', '');
  const a = h.length === 8 ? parseInt(h.slice(6, 8), 16) / 255 : 1;
  return [`0x${h.slice(0, 6)}`, a.toFixed(3)];
}

function tokensSwift(projectRoot) {
  const t = JSON.parse(fs.readFileSync(path.join(projectRoot, 'constants', 'tokens.json'), 'utf8'));
  const lines = Object.keys(t.light).map((k) => {
    const [l, la] = rgba(t.light[k]);
    const [d, da] = rgba(t.dark[k] ?? t.light[k]);
    return `    static let ${camel(k)} = c(${l}, ${la}, ${d}, ${da})`;
  });
  const cats = Object.keys(t.light).filter((k) => k.startsWith('cat/') && !k.endsWith('-tint')).map((k) => k.slice(4));
  return `// Generated by plugins/withWidget.js from constants/tokens.json. Do not edit.
import SwiftUI
import UIKit

enum Tok {
    static func c(_ light: UInt32, _ la: Double, _ dark: UInt32, _ da: Double) -> Color {
        func ui(_ v: UInt32, _ a: Double) -> UIColor {
            UIColor(red: CGFloat((v >> 16) & 0xFF) / 255, green: CGFloat((v >> 8) & 0xFF) / 255, blue: CGFloat(v & 0xFF) / 255, alpha: a)
        }
        return Color(UIColor { $0.userInterfaceStyle == .dark ? ui(dark, da) : ui(light, la) })
    }

${lines.join('\n')}

    /// Tile background for a category or status tone.
    static func tint(_ tone: String) -> Color {
        switch tone {
${cats.map((c) => `        case "${c}": return ${camel('cat/' + c + '-tint')}`).join('\n')}
        case "warn": return statusWarnTint
        case "success": return statusSuccessTint
        case "danger": return statusDangerTint
        case "accent": return brandAccentTint
        default: return bgMuted
        }
    }

    /// Icon colour for a category or status tone.
    static func fg(_ tone: String) -> Color {
        switch tone {
${cats.map((c) => `        case "${c}": return ${camel('cat/' + c)}`).join('\n')}
        case "warn": return statusWarn
        case "success": return statusSuccess
        case "danger": return statusDanger
        case "accent": return brandAccentText
        default: return textSecondary
        }
    }
}
`;
}

// ─── Step 1–3: files ─────────────────────────────────────────────────────────

function withFiles(config) {
  return withDangerousMod(config, [
    'ios',
    (mod) => {
      const dir = path.join(mod.modRequest.platformProjectRoot, EXT_NAME);
      fs.mkdirSync(dir, { recursive: true });

      fs.copyFileSync(path.join(SRC, 'LogItWidget.swift'), path.join(dir, 'LogItWidget.swift'));
      fs.copyFileSync(path.join(SRC, `${EXT_NAME}.entitlements`), path.join(dir, `${EXT_NAME}.entitlements`));
      const plist = fs
        .readFileSync(path.join(SRC, 'Info.plist'), 'utf8')
        .replace('__APP_VERSION__', config.version || '1.0.0')
        .replace('__BUILD_NUMBER__', config.ios?.buildNumber || '1');
      fs.writeFileSync(path.join(dir, 'Info.plist'), plist);
      fs.writeFileSync(path.join(dir, 'Tokens.swift'), tokensSwift(mod.modRequest.projectRoot));

      const fontRoot = path.dirname(require.resolve('@expo-google-fonts/manrope/package.json', { paths: [mod.modRequest.projectRoot] }));
      for (const f of FONTS) {
        const weightDir = f.split('_')[1];
        fs.copyFileSync(path.join(fontRoot, weightDir, `${f}.ttf`), path.join(dir, `${f}.ttf`));
      }
      return mod;
    },
  ]);
}

// ─── Step 4: Xcode target ────────────────────────────────────────────────────

function withTarget(config) {
  return withXcodeProject(config, (mod) => {
    const proj = mod.modResults;
    const objects = proj.hash.project.objects;
    const exists = Object.values(objects.PBXNativeTarget || {}).some((t) => typeof t === 'object' && unquote(t.name) === EXT_NAME);
    if (exists) return mod;

    const bundleId = `${mod.ios?.bundleIdentifier ?? 'com.ama.spendingtracker'}.${EXT_NAME}`;
    if (!objects.PBXTargetDependency) objects.PBXTargetDependency = {};
    if (!objects.PBXContainerItemProxy) objects.PBXContainerItemProxy = {};

    const group = proj.addPbxGroup([], EXT_NAME, EXT_NAME);
    proj.addToPbxGroup(group.uuid, proj.getFirstProject().firstProject.mainGroup);

    const target = proj.addTarget(EXT_NAME, 'app_extension', EXT_NAME, bundleId);
    // addTarget creates no build phases; without our own, files land in the main target.
    proj.addBuildPhase([], 'PBXSourcesBuildPhase', 'Sources', target.uuid);
    proj.addBuildPhase([], 'PBXResourcesBuildPhase', 'Resources', target.uuid);
    proj.addBuildPhase([], 'PBXFrameworksBuildPhase', 'Frameworks', target.uuid);

    for (const f of SWIFT_FILES) proj.addSourceFile(f, { target: target.uuid }, group.uuid);

    // Fonts: file reference in the group, build file in this target's Resources phase.
    const resPhase = Object.entries(objects.PBXResourcesBuildPhase).find(([uuid]) =>
      (objects.PBXNativeTarget[target.uuid].buildPhases || []).some((p) => p.value === uuid),
    );
    for (const f of FONTS) {
      const file = proj.addFile(`${f}.ttf`, group.uuid, { lastKnownFileType: 'file' });
      if (!file) continue;
      file.uuid = proj.generateUuid();
      file.target = target.uuid;
      proj.addToPbxBuildFileSection(file);
      resPhase[1].files.push({ value: file.uuid, comment: `${f}.ttf in Resources` });
    }
    proj.addFile('Info.plist', group.uuid, { defaultEncoding: 4 });
    proj.addFile(`${EXT_NAME}.entitlements`, group.uuid, { defaultEncoding: 4 });

    const list = objects.XCConfigurationList[target.pbxNativeTarget.buildConfigurationList];
    for (const { value } of list?.buildConfigurations ?? []) {
      const cfg = objects.XCBuildConfiguration[value];
      if (!cfg?.buildSettings) continue;
      Object.assign(cfg.buildSettings, {
        ALWAYS_EMBED_SWIFT_STANDARD_LIBRARIES: '"NO"',
        ASSETCATALOG_COMPILER_WIDGET_BACKGROUND_COLOR_NAME: '""',
        CLANG_ENABLE_MODULES: '"YES"',
        CODE_SIGN_ENTITLEMENTS: `"${EXT_NAME}/${EXT_NAME}.entitlements"`,
        INFOPLIST_FILE: `"${EXT_NAME}/Info.plist"`,
        // containerBackground and contentMarginsDisabled need iOS 17.
        IPHONEOS_DEPLOYMENT_TARGET: '"17.0"',
        LD_RUNPATH_SEARCH_PATHS: '"$(inherited) @executable_path/Frameworks @executable_path/../../Frameworks"',
        PRODUCT_BUNDLE_IDENTIFIER: `"${bundleId}"`,
        SKIP_INSTALL: '"YES"',
        SWIFT_VERSION: '"5.0"',
        TARGETED_DEVICE_FAMILY: '"1,2"',
        ...(mod.ios?.appleTeamId && { DEVELOPMENT_TEAM: mod.ios.appleTeamId }),
      });
    }
    return mod;
  });
}

module.exports = function withWidget(config) {
  config = withFiles(config);
  config = withTarget(config);
  return config;
};
