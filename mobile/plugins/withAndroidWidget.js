// Expo Config Plugin — LogIt home-screen widgets for Android.
// Figma 1037:4555 ("Android": same layouts as iOS, resizable, 28dp corners).
//
// At `expo prebuild` time:
//  1. Copies plugins/android/widget/LogItWidgets.kt and its res/ tree
//  2. Generates colours (values + values-night) from constants/tokens.json
//  3. Generates vector icons from the same Hugeicons the app uses
//  4. Copies the Manrope fonts into res/font
//  5. Registers the Spending and To check widget receivers
// The widgets read the snapshot written by lib/widget-snapshot.ts.

const { withAndroidManifest, withDangerousMod } = require('@expo/config-plugins');
const path = require('path');
const fs = require('fs');

const SRC = path.join(__dirname, 'android', 'widget');

// Widget icon → Hugeicons name (same mapping as components/ui/icon.tsx).
const ICONS = {
  flash: 'FlashIcon',
  inbox: 'InboxIcon',
  tick: 'Tick02Icon',
  mic: 'Mic01Icon',
  paste: 'BubbleChatAddIcon',
  sparkle: 'AiMagicIcon',
  more: 'MoreHorizontalIcon',
  receive: 'ArrowDownLeft01Icon',
  people: 'UserGroupIcon',
  food: 'Restaurant01Icon',
  transport: 'Car01Icon',
  shopping: 'ShoppingBag02Icon',
  bills: 'Invoice01Icon',
  airtime: 'SmartPhone01Icon',
  subscription: 'RepeatIcon',
  cash: 'Money03Icon',
  loans: 'Coins01Icon',
  fees: 'Tag01Icon',
};

const FONTS = {
  manrope_medium: ['500Medium', 'Manrope_500Medium.ttf'],
  manrope_semibold: ['600SemiBold', 'Manrope_600SemiBold.ttf'],
  manrope_bold: ['700Bold', 'Manrope_700Bold.ttf'],
  manrope_extrabold: ['800ExtraBold', 'Manrope_800ExtraBold.ttf'],
};

function copyDir(from, to) {
  fs.mkdirSync(to, { recursive: true });
  for (const e of fs.readdirSync(from, { withFileTypes: true })) {
    const a = path.join(from, e.name);
    const b = path.join(to, e.name);
    if (e.isDirectory()) copyDir(a, b);
    else fs.copyFileSync(a, b);
  }
}

// ─── Colours ─────────────────────────────────────────────────────────────────

// tokens.json uses #RRGGBB or #RRGGBBAA; Android wants #AARRGGBB.
const androidHex = (hex) => {
  const h = hex.replace('#', '').toUpperCase();
  return h.length === 8 ? `#${h.slice(6)}${h.slice(0, 6)}` : `#${h}`;
};
const colorName = (k) => `logit_${k.replace(/[/-]/g, '_')}`;

function colorsXml(map) {
  const rows = Object.entries(map).map(([k, v]) => `    <color name="${colorName(k)}">${androidHex(v)}</color>`);
  return `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by plugins/withAndroidWidget.js from constants/tokens.json. -->\n<resources>\n${rows.join('\n')}\n</resources>\n`;
}

// ─── Icons ───────────────────────────────────────────────────────────────────

function loadIcon(projectRoot, name) {
  const dir = path.dirname(require.resolve('@hugeicons/core-free-icons/package.json', { paths: [projectRoot] }));
  const src = fs.readFileSync(path.join(dir, 'dist', 'esm', `${name}.js`), 'utf8');
  const start = src.indexOf('[');
  const end = src.lastIndexOf('];');
  // The file is a plain array literal of [tag, attrs] pairs.
  return new Function(`return ${src.slice(start, end + 1)}`)();
}

const circlePath = (cx, cy, r) => `M${cx - r},${cy} a${r},${r} 0 1,0 ${2 * r},0 a${r},${r} 0 1,0 ${-2 * r},0`;
function rectPath(x, y, w, h, rx = 0) {
  if (!rx) return `M${x},${y} h${w} v${h} h${-w} Z`;
  return `M${x + rx},${y} h${w - 2 * rx} a${rx},${rx} 0 0 1 ${rx},${rx} v${h - 2 * rx} a${rx},${rx} 0 0 1 ${-rx},${rx} h${-(w - 2 * rx)} a${rx},${rx} 0 0 1 ${-rx},${-rx} v${-(h - 2 * rx)} a${rx},${rx} 0 0 1 ${rx},${-rx} Z`;
}

// White icons; the layouts and Kotlin tint them with token colours.
function vectorXml(elements) {
  const paths = elements.map(([tag, a]) => {
    const n = (v) => Number(v || 0);
    const d =
      tag === 'path' ? a.d
        : tag === 'circle' ? circlePath(n(a.cx), n(a.cy), n(a.r))
          : tag === 'rect' ? rectPath(n(a.x), n(a.y), n(a.width), n(a.height), n(a.rx))
            : null;
    if (!d) return '';
    const stroked = a.stroke && a.stroke !== 'none';
    const filled = a.fill ? a.fill !== 'none' : !stroked;
    return [
      `    <path android:pathData="${d}"`,
      filled ? ' android:fillColor="#FFFFFFFF"' : '',
      a.fillRule === 'evenodd' ? ' android:fillType="evenOdd"' : '',
      stroked ? ` android:strokeColor="#FFFFFFFF" android:strokeWidth="${a.strokeWidth || 1.5}"` : '',
      stroked && a.strokeLinecap ? ` android:strokeLineCap="${a.strokeLinecap}"` : '',
      stroked && a.strokeLinejoin ? ` android:strokeLineJoin="${a.strokeLinejoin}"` : '',
      '/>',
    ].join('');
  });
  return `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by plugins/withAndroidWidget.js from Hugeicons. -->\n<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="24dp" android:height="24dp" android:viewportWidth="24" android:viewportHeight="24">\n${paths.filter(Boolean).join('\n')}\n</vector>\n`;
}

// ─── Files ───────────────────────────────────────────────────────────────────

function withFiles(config) {
  return withDangerousMod(config, [
    'android',
    (mod) => {
      const root = mod.modRequest.projectRoot;
      const main = path.join(mod.modRequest.platformProjectRoot, 'app', 'src', 'main');
      const res = path.join(main, 'res');

      const javaDir = path.join(main, 'java', 'com', 'ama', 'spendingtracker');
      fs.mkdirSync(javaDir, { recursive: true });
      fs.copyFileSync(path.join(SRC, 'LogItWidgets.kt'), path.join(javaDir, 'LogItWidgets.kt'));
      copyDir(path.join(SRC, 'res'), res);

      const tokens = JSON.parse(fs.readFileSync(path.join(root, 'constants', 'tokens.json'), 'utf8'));
      fs.mkdirSync(path.join(res, 'values'), { recursive: true });
      fs.mkdirSync(path.join(res, 'values-night'), { recursive: true });
      fs.writeFileSync(path.join(res, 'values', 'logit_widget_colors.xml'), colorsXml(tokens.light));
      fs.writeFileSync(path.join(res, 'values-night', 'logit_widget_colors.xml'), colorsXml({ ...tokens.light, ...tokens.dark }));

      fs.mkdirSync(path.join(res, 'drawable'), { recursive: true });
      for (const [file, name] of Object.entries(ICONS)) {
        fs.writeFileSync(path.join(res, 'drawable', `logit_ic_${file}.xml`), vectorXml(loadIcon(root, name)));
      }

      const fontDir = path.dirname(require.resolve('@expo-google-fonts/manrope/package.json', { paths: [root] }));
      fs.mkdirSync(path.join(res, 'font'), { recursive: true });
      for (const [res_, [dir, file]] of Object.entries(FONTS)) {
        fs.copyFileSync(path.join(fontDir, dir, file), path.join(res, 'font', `${res_}.ttf`));
      }
      return mod;
    },
  ]);
}

// ─── Manifest ────────────────────────────────────────────────────────────────

const RECEIVERS = [
  ['.SpendingWidget', 'Spending', '@xml/logit_widget_spending'],
  ['.ToCheckWidget', 'To check', '@xml/logit_widget_tocheck'],
];

function withReceivers(config) {
  return withAndroidManifest(config, (mod) => {
    const app = mod.modResults.manifest.application[0];
    app.receiver = app.receiver || [];
    for (const [name, label, info] of RECEIVERS) {
      if (app.receiver.some((r) => r.$['android:name'] === name)) continue;
      app.receiver.push({
        $: { 'android:name': name, 'android:label': label, 'android:exported': 'false' },
        'intent-filter': [{ action: [{ $: { 'android:name': 'android.appwidget.action.APPWIDGET_UPDATE' } }] }],
        'meta-data': [{ $: { 'android:name': 'android.appwidget.provider', 'android:resource': info } }],
      });
    }
    return mod;
  });
}

module.exports = function withAndroidWidget(config) {
  config = withFiles(config);
  config = withReceivers(config);
  return config;
};
